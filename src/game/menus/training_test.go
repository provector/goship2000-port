func retainedTraining(t *testing.T, suspended, cross, cold bool, cacheZero ...gamestate.CampaignCachePresence) (*FrontEnd, []byte) {
	t.Helper()
	c := missionController(t)
	a, err := assetdata.LoadFrontEndAssets(os.Getenv("GS2000_TEST_MISSIONS"))
	if err != nil {
		t.Fatal(err)
	}
	c.Office.Assets, c.Menus = a, a.Menus
	c.simulationProfile = "" // Exercise ordinary startup's frozen R5 default.
	c.Runtime.DisableEnemyAI = true
	next := c.Store.State()
	p := next.SelectedPilot()
	p.Rank, p.MissionType, p.Theatre = gamestate.RankCaptain, gamestate.MissionCampaign, gamestate.TheatrePersianGulf
	p.LegacyRaw[0x54], p.LegacyRaw[0x55], p.LegacyRaw[0x56] = 7, 5, 1
	p.SquadronPilots, err = gamestate.InitializeSquadron(p, next.Slots[:], a.Missions.Preflight.SquadronNames, rand.New(rand.NewSource(44)).Intn)
	if err != nil {
		t.Fatal(err)
	}
	camp, err := prepareMissionSession(a.Missions, p, 21, nil, nil, true)
	if err != nil {
		t.Fatal(err)
	}
	p.Campaign, err = gamestate.CloneCampaign(camp.CampaignDraft)
	if err != nil {
		t.Fatal(err)
	}
	p.LegacyRaw[0x4f], p.LegacyRaw[0x57] = 1, byte(p.Theatre.Raw())
	p.LegacyRaw[0x58] = byte(p.Campaign.ScenarioOrdinal)
	if suspended {
		if err = campaignSuspend(p, camp); err != nil {
			t.Fatal(err)
		}
	}
	if len(cacheZero) > 0 {
		// Complete supplied ordinal0 comparison payload, unrelated to Training.
		// It is never a claim that this file was generated by the Campaign above.
		for i := range p.Campaign.CacheInventory {
			if p.Campaign.CacheInventory[i].Ordinal == 0 {
				p.Campaign.CacheInventory[i].Presence = cacheZero[0]
			}
		}
		if cacheZero[0] == gamestate.CampaignCachePresent {
			p.Campaign.Caches = append(p.Campaign.Caches, gamestate.CampaignFormationCache{Scenario: "UNRELATED_00.SNR", World: "UNRELATED_00.WRL", Ordinal: 0, BeforeCount: 9})
		}
	}
	p.MissionType = gamestate.MissionTraining
	if cross {
		p.Theatre = gamestate.TheatreCentralEurope
	}
	if err = c.Store.Commit(next); err != nil {
		t.Fatal(err)
	}
	before := filmJSON(p.Campaign)
	if cold {
		c.Store, err = gamestate.OpenSaveStore(c.Store.Directory, "")
		if err != nil {
			t.Fatal(err)
		}
	} else {
		// A recognizable unrelated process-prefix must not leak into Training.
		c.retainedMissionObject = bytes.Repeat([]byte{0x55}, 32)
	}
	if err = c.enterMission(); err != nil {
		t.Fatal(err)
	}
	if c.Mission == nil || c.Mission.CampaignDraft != nil {
		t.Fatal("Training acquired Campaign draft")
	}
	if len(c.Mission.Data.Inputs.RetainedObject) != 0 {
		t.Fatal("Training borrowed warm Campaign prefix")
	}
	final, err := finalPreflight(c.Mission)
	if err != nil {
		t.Fatal(err)
	}
	c.Mission.Final = final
	switches, err := gamestate.LaunchSwitches(final.Mission, final.Settings, a.Missions.Generation.Tables.Initialization.CPGMapping)
	if err != nil {
		t.Fatal(err)
	}
	c.enemyLaunchRules, err = freezePreparedEnemyRules(a.Missions, final.Mission, switches, true)
	if err != nil {
		t.Fatal(err)
	}
	if err = c.constructSimulation(final); err != nil {
		t.Fatal(err)
	}
	if c.Mission.ResultLaunch == nil || c.Mission.ResultUnavailable != "" || !c.Rendering.r5Mechanics || c.Rendering.Initialized.Switches&0x400 == 0 {
		t.Fatal("retained-Campaign Training admission", c.Mission.ResultUnavailable)
	}
	if !bytes.Equal(before, filmJSON(c.Store.State().SelectedPilot().Campaign)) {
		t.Fatal("Training preparation changed Campaign")
	}
	return c, before
}

func TestTrainingDoesNotRequireUnrelatedCacheZero(t *testing.T) {
	for _, presence := range []gamestate.CampaignCachePresence{gamestate.CampaignCachePresent, gamestate.CampaignCacheAbsent, gamestate.CampaignCacheUnknown} {
		t.Run(string(presence), func(t *testing.T) {
			c, before := retainedTraining(t, false, true, false, presence)
			if c.Mission.ResultLaunch == nil || !bytes.Equal(before, filmJSON(c.Store.State().SelectedPilot().Campaign)) {
				t.Fatal("cache0 affected Training admission")
			}
		})
	}
}

func TestTrainingRetainedCampaignOwnershipMatrix(t *testing.T) {
	for _, suspended := range []bool{false, true} {
		for _, cross := range []bool{false, true} {
			for _, cold := range []bool{false, true} {
				t.Run(fmt.Sprintf("suspended%t/cross%t/cold%t", suspended, cross, cold), func(t *testing.T) {
					c, before := retainedTraining(t, suspended, cross, cold)
					if got, err := resultDigest(c.Store.State().SelectedPilot().Campaign); err != nil || got != c.Mission.ResultLaunch.RetainedCampaignSHA256 {
						t.Fatal("launch lost independent Campaign fingerprint", got, err)
					}
					if !bytes.Equal(before, filmJSON(c.Store.State().SelectedPilot().Campaign)) {
						t.Fatal("Campaign changed")
					}
				})
			}
		}
	}
}

func TestTrainingCommitRestartFilmResumeAndCampaignReturn(t *testing.T) {
	c, campaign := retainedTraining(t, true, true, true)
	c.FilmDirectory = t.TempDir()
	stats := *c.Store.State().SelectedPilot().Statistics
	c.beginFilmRecording(c.Mission.Final)
	defer c.AbandonFilmRecording()
	for _, action := range []Actions{{}, {EndMission: true}, {}, {ConfirmQuit: true}} {
		if err := c.Handle(action); err != nil {
			t.Fatal(err)
		}
	}
	if c.Screen != ScreenDebrief {
		t.Fatal("normal ending did not reach debrief", c.Screen, c.Message)
	}
	film := verifyFilm(t, c)
	if !film.SafeGameplayMechanics() {
		t.Fatal("new policy not recorded", film.Header)
	}
	id := c.Debrief.Pending.Start.ID
	loopAcknowledge(t, c)
	p := c.Store.State().SelectedPilot()
	if !bytes.Equal(campaign, filmJSON(p.Campaign)) || p.Statistics.CareerScore != stats.CareerScore || p.Statistics.MissionCampaignCounter != stats.MissionCampaignCounter || p.Statistics.LastMissionScore != stats.LastMissionScore {
		t.Fatal("Training changed retained Campaign/career score", p.Statistics, stats)
	}
	pending, err := c.Store.PendingSortie()
	if err != nil || pending != nil {
		t.Fatal("Training still pending", err)
	}
	durable, err := os.ReadFile(filepath.Join(c.Store.Directory, "sorties", id+".json"))
	if err != nil {
		t.Fatal(err)
	}
	var committedRecord gamestate.PendingSortie
	if err = json.Unmarshal(durable, &committedRecord); err != nil || committedRecord.Phase != gamestate.SortieCommitted {
		t.Fatal("Training not committed", err)
	}
	committed := filmJSON(c.Store.State())
	if err = c.Store.CommitSortie(id); err != nil || !bytes.Equal(committed, filmJSON(c.Store.State())) {
		t.Fatal("duplicate acknowledgment", err)
	}
	reopened, err := gamestate.OpenSaveStore(c.Store.Directory, "")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(campaign, filmJSON(reopened.State().SelectedPilot().Campaign)) {
		t.Fatal("Campaign lost on restart")
	}
	options := c.Runtime
	options.DisableEnemyAI, options.DisableWingmenAI = false, true
	view, err := NewFilmPlayback(c.Office.Assets, film, options)
	if err != nil {
		t.Fatal(err)
	}
	for !view.Done {
		if err = view.Step(); err != nil {
			t.Fatal(err)
		}
	}
	view, err = NewFilmPlayback(c.Office.Assets, film, options)
	if err != nil {
		t.Fatal(err)
	}
	if err = view.Resume(); err != nil || view.Engine.Store != nil || view.Engine.Mission.ResultLaunch != nil {
		t.Fatal("Resume career isolation", err)
	}
	if !bytes.Equal(committed, filmJSON(c.Store.State())) {
		t.Fatal("replay/Resume changed career")
	}
	next := reopened.State()
	p = next.SelectedPilot()
	p.MissionType, p.Theatre = gamestate.MissionCampaign, p.Campaign.Theatre
	if err = reopened.Commit(next); err != nil {
		t.Fatal(err)
	}
	s, err := prepareMissionSession(c.Office.Assets.Missions, p, 21, nil, nil, true)
	if err != nil || s.CampaignDraft == nil || s.CampaignDraft.Phase != gamestate.CampaignActive || s.Data.World != p.Campaign.Suspended.Mission.World {
		t.Fatal("retained suspended Campaign return", err)
	}
	if out := os.Getenv("GS2000_R5_OUTPUT"); out != "" {
		raw, e := replay.Marshal(film)
		if e != nil {
			t.Fatal(e)
		}
		if e = os.WriteFile(filepath.Join(out, "r5-training-retained-campaign.g2r"), raw, 0600); e != nil {
			t.Fatal(e)
		}
		receipt, _ := json.MarshalIndent(map[string]any{"film": film.Header.ID, "career_committed_once": true, "retained_campaign_unchanged": true, "strict": true, "isolated_resume": true, "scope": "Actual production Training launch/normal ending/ack from supplied fresh retained-Campaign state; no success/award injected"}, "", "  ")
		_ = os.WriteFile(filepath.Join(out, "r5-training.json"), receipt, 0600)
	}
}
